ORDINAL_PREFIX = re.compile(r"^(?:первый|второй|третий|первая|вторая|третья)\s+")


def canonical_enemy_key(enemy_name: str) -> str:
    name = re.sub(r"\s+", " ", str(enemy_name)).strip().casefold().replace("ё", "е")
    return ORDINAL_PREFIX.sub("", name)


def iter_battle_text_rows():
    """Yield database seed rows; INSERT IGNORE preserves operator-edited phrases."""
    for enemy_key, phases in [("*", GENERIC_BATTLE_TEXT), *ENEMY_BATTLE_TEXT.items()]:
        for phase, variants in phases.items():
            for variant_no, template_text in enumerate(variants, start=1):
                if enemy_key != "*" and phase == "wounded":
                    template_text = re.sub(
                        r"\b(удар|выпад) \{actor\}",
                        lambda match: f"{match.group(1)} {{actor_genitive}}",
                        template_text,
                        flags=re.IGNORECASE,
                    )
                yield (enemy_key, phase, variant_no, template_text)
